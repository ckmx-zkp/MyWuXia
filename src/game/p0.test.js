test('fixed dialogue branch leads to actual shop and teaching consequences without duplicate rewards', () => {
  let s = at(fresh(), 'pharmacy');
  s = cmd(s, 'DISCOVER_EVENT', { id: 'medicine' });
  s = cmd(s, 'CHOOSE_EVENT', { id: 'medicine', choice: 'accept' });
  s = at(s, 'dock');
  const blocked = cmd(s, 'CHOOSE_EVENT', { id: 'medicine', choice: 'reason' });
  assert.equal(blocked.p0.quests.medicine.node, 'road');
  s.p0.knowledge = 3; s.p0.materials.herbs = 2;
  s = cmd(s, 'CHOOSE_EVENT', { id: 'medicine', choice: 'reason' });
  assert.equal(s.p0.quests.medicine.node, 'delivered'); assert.equal(s.p0.materials.herbs, 0);
  s = at(s, 'home');
  s = cmd(s, 'CHOOSE_EVENT', { id: 'medicine', choice: 'finish' });
  assert.ok(s.p0.facts.medicine_complete);
  assert.equal(cmd(s, 'CHOOSE_EVENT', { id: 'medicine', choice: 'finish' }).silver, s.silver);
  assert.ok(s.p0.journal.some(j => j.choiceId === 'reason' && j.result === 'success'));
  s = at(s, 'gym'); s = cmd(s, 'LEARN_SKILL', { id: 'huashan' });
  assert.ok(s.p0.styles['华山剑法']);
  assert.deepEqual(restore(s), { ...s, fx: null });
});
test('side battle restores its continuation, retreat opens repair and cannot duplicate story rewards', () => {
  let s = cmd(at(fresh(), 'pharmacy'), 'DISCOVER_EVENT', { id: 'medicine' });
  s = cmd(s, 'CHOOSE_EVENT', { id: 'medicine', choice: 'accept' });
  s = cmd(at(s, 'dock'), 'CHOOSE_EVENT', { id: 'medicine', choice: 'fight' });
  assert.equal(s.p0.quests.medicine.pending, 'fight');
  assert.deepEqual(advanceCombat(s, settleP0Combat), advanceCombat(restore(s), settleP0Combat));
  const escaped = retreatCombat(restore(s), settleP0Combat);
  assert.equal(escaped.p0.quests.medicine.node, 'repair'); assert.equal(escaped.p0.quests.medicine.pending, null);
  assert.equal(retreatCombat(escaped, settleP0Combat).silver, escaped.silver);
  assert.deepEqual(restore(escaped), { ...escaped, fx: null });
});
