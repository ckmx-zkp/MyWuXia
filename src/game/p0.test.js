test('complete legal command route earns, learns, trains, wins the actual escort and unlocks teaching', () => {
  const reducer = createGameReducer({ tick: state => state.action?.type === 'combat' ? advanceCombat(state, settleP0Combat) : state });
  let s = fresh(), now = 1000;
  const send = (type, fields = {}) => { s = reducer(s, { type, ...fields }, now); };
  const walk = (...rooms) => rooms.forEach(id => { send('MOVE_ROOM', { id }); assert.equal(s.p0.room, id); });
  walk('street', 'gym', 'dock');
  send('START_ACTIVITY', { id: 'work' }); now += 600000; send('HEARTBEAT');
  walk('gym'); send('LEARN_SKILL', { id: 'taizu' });
  send('START_ACTIVITY', { id: 'style', target: '太祖长拳' }); now += 100000; send('HEARTBEAT');
  send('EQUIP_LOADOUT', { loadout: { ...s.loadout, style: '太祖长拳' } });
  send('START_ACTIVITY', { id: 'rest' }); now += 100000; send('HEARTBEAT');
  walk('street', 'market', 'pharmacy'); send('DISCOVER_EVENT', { id: 'medicine' });
  send('CHOOSE_EVENT', { id: 'medicine', choice: 'accept' });
  walk('market', 'street', 'gym', 'dock'); send('CHOOSE_EVENT', { id: 'medicine', choice: 'fight' });
  s = restore(s);
  for (let i = 0; i < 60 && s.battle.status === 'active'; i++) { now += 1000; send('HEARTBEAT'); }
  assert.equal(s.battle.status, 'won'); assert.equal(s.p0.quests.medicine.node, 'delivered');
  assert.ok(s.mp < 100); send('CLOSE_COMBAT');
  walk('gym', 'street', 'inn', 'alley', 'home'); send('CHOOSE_EVENT', { id: 'medicine', choice: 'finish' });
  walk('alley', 'inn', 'street', 'gym'); send('LEARN_SKILL', { id: 'huashan' });
  assert.ok(s.p0.styles['华山剑法']); assert.ok(s.p0.facts.medicine_complete);
  assert.deepEqual(restore(s), { ...s, fx: null });
});
