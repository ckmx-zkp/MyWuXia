import { readFile, writeFile } from 'node:fs/promises';
const ids = ['YZ-01', 'FZ-01', 'JX-01', 'SZ-01', 'HZ-01', 'WX-01', 'DL-01', 'DL-02'];
const index = {};
for (const id of ids) {
  const { default: tree } = await import(`../src/content/quests/${id}.js`);
  index[id] = { id, name: tree.name, where: tree.where,
    nodes: tree.nodes.map(n => ({ choices: n.choices.map(c => ({ ...(c.combat ? { combat: c.combat } : {}), ...(c.failCombat ? { failCombat: c.failCombat } : {}) })) })) };
}
const output = '// Generated by scripts/sync-quest-index.mjs; edit the quest source.\nexport const QUEST_INDEX = ' + JSON.stringify(index) + ';\n';
const path = new URL('../src/content/quest-index.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Quest index is stale. Run npm run content:index.');
} else await writeFile(path, output, 'utf8');
